import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "sim"))
import faults as FT  # noqa: E402

METH = [("range", "Range check", "#a371f7"), ("range_hold", "Range + HOLD rule", "#d29922"),
        ("crewwatch", "CrewWatch", "#58a6ff")]


def wilson(k, n, z=1.96):
    if n == 0:
        return (0.0, 0.0)
    p = k / float(n)
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * ((p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5) / d
    return (max(0.0, c - h), min(1.0, c + h))


def svg(res, path):
    types = sorted(res["by_type"], key=int)
    W, H = 760, 300
    L, B = 60, 60
    gw = (W - L - 20) / float(len(types))
    bw = gw / 4.0
    o = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 %d %d" font-family="system-ui,sans-serif" font-size="12">' % (W, H),
         '<rect width="100%" height="100%" fill="#ffffff"/>']
    for p in (0, 25, 50, 75, 100):
        y = H - B - (H - B - 20) * p / 100.0
        o.append('<line x1="%d" x2="%d" y1="%.1f" y2="%.1f" stroke="#e5e7eb"/>' % (L, W - 20, y, y))
        o.append('<text x="%d" y="%.1f" text-anchor="end" fill="#555">%d%%</text>' % (L - 6, y + 4, p))
    for gi, t in enumerate(types):
        row = res["by_type"][t]
        x0 = L + gi * gw + bw * 0.5
        for mi, (k, _, col) in enumerate(METH):
            r = row[k]["rate"]
            h = (H - B - 20) * r
            x = x0 + mi * bw
            o.append('<rect x="%.1f" y="%.1f" width="%.1f" height="%.1f" fill="%s"/>' % (x, H - B - h, bw * 0.9, h, col))
            o.append('<text x="%.1f" y="%.1f" text-anchor="middle" fill="#333" font-size="10">%d</text>' % (
                x + bw * 0.45, H - B - h - 3, round(100 * r)))
        nm = FT.TYPES[int(t)][1]
        o.append('<text x="%.1f" y="%d" text-anchor="middle" fill="#111">%s. %s</text>' % (L + gi * gw + gw / 2, H - B + 16, t, nm[:22]))
        o.append('<text x="%.1f" y="%d" text-anchor="middle" fill="#777" font-size="10">n=%d</text>' % (
            L + gi * gw + gw / 2, H - B + 30, row["crewwatch"]["n"]))
    for mi, (_, lbl, col) in enumerate(METH):
        o.append('<rect x="%d" y="%d" width="10" height="10" fill="%s"/><text x="%d" y="%d">%s</text>' % (
            L + mi * 170, H - 18, col, L + mi * 170 + 14, H - 9, lbl))
    o.append('</svg>')
    with open(path, "w") as f:
        f.write("\n".join(o))


def main():
    with open(os.path.join(HERE, "results.json")) as f:
        res = json.load(f)
    m = res["model"]
    lim = res["limits"]
    fa = res["fa"]
    cl = res["clean"]
    lines = ["# RESULTS — three detectors, same telemetry, matched false-alarm budget", "",
             "Generated by `eval/report.py` from `eval/results.json` (`eval/evaluate.py`). Do not edit by hand.", "",
             "**Setup.** PPG-DaLiA, person-wise split: train S1–S8, validation S9–S11, test (the crew) S12–S15. "
             "Faults injected only into test recordings, on top of the real signals. All CrewWatch scores are "
             "computed by the integer flight C code (`tinyinfer`) through ctypes.", "",
             "**Matched budget.** Every detector's threshold is chosen on validation subjects so that at most "
             "%.1f %% of normal ticks alarm. Range limits: train min/max widened by k = %.2f × range "
             "(validation FA %.3f %%). HOLD limits (ticks unchanged): %s." % (
                 100 * m["fa_budget"], lim["k"], 100 * lim["val_fa"],
                 ", ".join("%s ≥ %d" % (k, v) for k, v in sorted(lim["hold_n"].items()))), "",
             "## Detection rate per injected event", "",
             "| Fault type | n | Range check | Range + HOLD | CrewWatch | median latency (s) R / R+H / CW |",
             "|---|---|---|---|---|---|"]
    for t in sorted(res["by_type"], key=int):
        row = res["by_type"][t]
        cells = []
        for k, _, _ in METH:
            r = row[k]
            lo, hi = wilson(r["detected"], r["n"])
            cells.append("%d/%d = **%.0f %%** <sub>[%.0f–%.0f]</sub>" % (r["detected"], r["n"], 100 * r["rate"], 100 * lo, 100 * hi))
        lat = " / ".join("—" if row[k]["median_latency_s"] is None else str(row[k]["median_latency_s"]) for k, _, _ in METH)
        lines.append("| %s. %s | %d | %s | %s |" % (t, FT.TYPES[int(t)][1], row["crewwatch"]["n"], " | ".join(cells), lat))
    lines += ["", "<sub>[a–b] = 95 % Wilson interval. Detected = at least one alarm tick between onset and end + 60 s.</sub>", "",
              "![detection](detection.svg)", "",
              "## False alarms on clean test data (realised, not tuned)", "",
              "| | Range check | Range + HOLD | CrewWatch |", "|---|---|---|---|",
              "| alarm ticks / clean ticks | %.3f %% | %.3f %% | %.3f %% |" % (100 * fa["range"], 100 * fa["range_hold"], 100 * fa["crewwatch"]),
              "| per hour (1 Hz) | %.1f | %.1f | %.1f |" % (3600 * fa["range"], 3600 * fa["range_hold"], 3600 * fa["crewwatch"]),
              "", "%d clean test ticks (after each person's %d-s baseline window)." % (cl["ticks"], 1200), "",
              "## Integer vs float", "",
              "Same int16 feature vectors scored by the int8 flight chain and by the float model `||sMx||²`, "
              "each at its own validation threshold:", "",
              "- decision disagreement on clean test ticks: **%.3f %%** (%d of %d)" % (
                  100.0 * cl["disagree"] / cl["ticks"], cl["disagree"], cl["ticks"]),
              "- decision agreement on validation: %.3f %%" % (100 * m["val_int_float_agreement"]), "",
              "## Model", "",
              "- F = %d features → %d-byte int8 weight table (F ≤ 25: same shape class as the board-measured model)" % (m["F"], m["weight_bytes"]),
              "- integer threshold %d" % m["threshold_int"], "",
              "## Which feature led the first CrewWatch alarm (count of events)", ""]
    for t, d in sorted(res["top_contributor_at_first_alarm"].items(), key=lambda kv: int(kv[0])):
        lines.append("- type %s: %s" % (t, ", ".join("%s ×%d" % kv for kv in sorted(d.items(), key=lambda kv: -kv[1]))))
    lines += ["", "## Reading this table honestly", "", "_Filled in by hand after looking at the numbers — see below._", ""]
    with open(os.path.join(HERE, "RESULTS.md"), "w") as f:
        f.write("\n".join(lines))
    svg(res, os.path.join(HERE, "detection.svg"))
    print("wrote eval/RESULTS.md, eval/detection.svg")
    return 0


if __name__ == "__main__":
    sys.exit(main())
